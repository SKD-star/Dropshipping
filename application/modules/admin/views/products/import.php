  var fd = new FormData();
  fd.append('supplier_slug', document.getElementById('cred_supplier_slug').value);
  fd.append('api_key', document.getElementById('cred_api_key').value);
  fd.append('api_secret', document.getElementById('cred_api_secret').value);
  fd.append('brand_name', document.getElementById('cred_brand_name').value);
  fd.append('auto_fulfill', document.getElementById('cred_auto_fulfill').value);
  fd.append('<?= $this->security->get_csrf_token_name() ?>', '<?= $this->security->get_csrf_hash() ?>');

  fetch('<?= base_url('admin/products/ajax_save_supplier_credentials') ?>', {
    method: 'POST',
    body: fd
  })
  .then(function(r){ return r.json(); })
  .then(function(res){
    if (res.success) {
      alert('✅ ' + res.message);
      $('#apiCredentialsModal').modal('hide');
    } else {
      alert(res.error || 'Failed to save credentials.');
    }
  });
}

